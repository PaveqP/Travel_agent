def support_letter(guide_id: str, state: dict, name: str = "[ваше имя]") -> dict:
    guide = next((g for g in GUIDES if g.id == guide_id), None)
    if guide is None:
        raise ValueError("Неизвестная ситуация")
    c = state.get("constraints", {})
    option = next((o for o in state.get("options", []) if o["id"] == state.get("selected")), {})
    stay = option.get("stay") or {}
    values = {"name": name, "hotel": stay.get("name") or c.get("hotel") or "[название отеля]",
              "destination": c.get("destination") or "[город назначения]",
              "origin": c.get("origin") or "[город отправления]", "start": c.get("start") or "[дата вылета]",
              "check_in": c.get("check_in") or c.get("start") or "[дата заезда]",
              "check_out": c.get("check_out") or c.get("end") or "[дата выезда]", "adults": c.get("adults") or "[число гостей]"}
    return {"id": guide.id, "title": guide.title, "description": guide.description, "steps": list(guide.steps),
            "subject": guide.subject.format_map(values), "letter": guide.template.format_map(values)}


def support_reply(message: str, state: dict) -> str | None:
    text = message.casefold()
    explicit = any(word in text for word in ("письм", "шаблон", "жалоб", "претенз", "задержали", "рейс отмен", "рейс перен", "потерял", "багаж не", "не заселя", "помоги с заселен"))
    incident = any(word in text for word in ("что делать", "проблем", "не отвечает", "отменили", "задержка", "не выдали")) and any(word in text for guide in GUIDES for word in guide.keywords)
    if not explicit and not incident:
        return None
    guide = next((g for g in (GUIDES[2], GUIDES[3], GUIDES[0], GUIDES[1]) if any(w in text for w in g.keywords)), GUIDES[1])
    data = support_letter(guide.id, state)
    return "\n\n".join([data["title"], "\n".join(f"{i + 1}. {s}" for i, s in enumerate(data["steps"])),
                           "Черновик письма. Заполните поля в квадратных скобках и проверьте факты перед отправкой.",
                           "Тема: " + data["subject"], data["letter"], "Письмо не отправлено. Используйте контакты поставщика из реального бронирования."])
